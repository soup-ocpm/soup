"""Run the original BPIC17 stages with SOUP's database and temporary HTTP CSV transport."""

from __future__ import annotations

import csv
import json
import logging
import re
import sys
from contextlib import contextmanager
from functools import wraps
from pathlib import Path
from time import perf_counter


def native_csv_query(function, directory: Path, url_for, **kwargs):
    """Adapt only PromG's CSV reader, retaining its record-creation query verbatim."""
    filename = kwargs["file_name"]
    url = url_for(filename)
    with (directory / filename).open(encoding="utf-8", newline="") as handle:
        columns = next(csv.reader(handle))
    # PromG's dtype mapping is generated by _determine_column_mapping_str.
    mapping = kwargs["mapping"]
    entries = re.findall(r'([^,{}]+):\{type:"(INTEGER|FLOAT|BOOLEAN)"\}', mapping)
    if (
        mapping not in ("", "{}")
        and "{"
        + ",".join(f'{column}:{{type:"{kind}"}}' for column, kind in entries)
        + "}"
        != mapping
    ):
        raise ValueError(
            "Unsupported PromG CSV type mapping; refusing to change import semantics"
        )
    types = dict(entries)
    if set(types) - set(columns):
        raise ValueError("PromG CSV type mapping references missing columns")
    properties = []
    for column in columns:
        key = "`" + column.replace("`", "``") + "`"
        value = f"csv_row.{key}"
        # APOC's nullValues:[""] also treats quoted empty strings as null.
        if mapping:
            value = f'CASE WHEN {value} = "" THEN null ELSE {value} END'
        if column in types:
            conversion = {
                "INTEGER": "toInteger",
                "FLOAT": "toFloat",
                "BOOLEAN": "toBoolean",
            }[types[column]]
            value = f"{conversion}({value})"
        properties.append(f"{key}: {value}")
    source = (
        f'LOAD CSV WITH HEADERS FROM "{url}" AS csv_row '
        + "WITH csv_row{.*, "
        + ", ".join(properties)
        + "} AS row RETURN row"
    )
    # The reader is inside apoc.periodic.iterate's existing string argument.
    source = source.replace("\\", "\\\\").replace("'", "\\'")
    query = function(**{**kwargs, "file_name": url})
    start = query.query_string.find('CALL apoc.load.csv("')
    marker = " yield map as row return row"
    end = query.query_string.find(marker, start)
    if start < 0 or end < 0 or query.query_string.count("CALL apoc.load.csv(") != 1:
        raise RuntimeError(
            "Unexpected PromG CSV reader; refusing to rewrite graph queries"
        )
    query.query_string = (
        query.query_string[:start] + source + query.query_string[end + len(marker) :]
    )
    return query


def compatible_constraint(query: str) -> str:
    """Drop only the obsolete provider hint; uniqueness and RANGE semantics stay intact."""
    if not query.lstrip().startswith("CREATE CONSTRAINT "):
        return query
    return re.sub(r"OPTIONS\s*\{\s*indexProvider\s*:\s*'range-1\.0'\s*\}", "", query)


def main(config_path: str) -> None:
    from csv_http import serve_csv
    from normalize import timed_phase
    from promg import (
        Configuration,
        DatabaseConnection,
        DatasetDescriptions,
        OcedPg,
        Performance,
        SemanticHeader,
    )
    from promg.modules.data_importer import di_ql
    from promg.modules.db_management import DBManagement
    from yaml import safe_load

    conf = Configuration.init_conf_with_config_file(path=Path(config_path))
    directory = Path(conf.import_directory)
    settings = safe_load(Path(config_path).read_text(encoding="utf-8"))

    metrics = {"duration_seconds": {}, "queries": {}}
    metrics_path = Path(config_path).parent / "worker-metrics.json"

    @contextmanager
    def measure(name):
        try:
            with timed_phase(metrics, name):
                yield
        finally:
            temporary = metrics_path.with_suffix(".tmp")
            temporary.write_text(json.dumps(metrics), encoding="utf-8")
            temporary.replace(metrics_path)

    def measured_csv(function):
        @wraps(function)
        def run(*args, **kwargs):
            with measure("csv_preparation"):
                return function(*args, **kwargs)

        return run

    class Connection(DatabaseConnection):
        def exec_query(self, function, **kwargs):
            self.query_name = function.__qualname__
            # Only the transport path changes; upstream query generators stay intact.
            if function is di_ql.get_create_nodes_by_loading_csv_query:
                with measure("csv_query_adapter"):
                    query = native_csv_query(function, directory, url_for, **kwargs)
                return super().exec_query(lambda: query)
            return super().exec_query(function, **kwargs)

        def _exec_query(self, query, database=None, **kwargs):
            if database is not None and database != self.db_name:
                raise RuntimeError(
                    "PromG attempted to query a different dataset database"
                )
            # Upstream catches and suppresses Neo4j exceptions. Let the worker fail
            # instead, while retaining its managed write-transaction behavior.
            query_started = perf_counter()
            original = query
            query = compatible_constraint(query)

            def redact(text):
                for secret in (conf.password, conf.uri, settings["csv_token"]):
                    if secret:
                        text = text.replace(secret, "[redacted]")
                return text

            logger = logging.getLogger(__name__)
            try:
                with self.driver.get_session(database=self.db_name) as session:
                    if query != original:
                        # Validate schema compatibility without creating any schema/data.
                        session.run("EXPLAIN " + query, kwargs).consume()
                        logger.info(
                            "PromG omitted obsolete range-1.0 provider hint database=%s",
                            self.db_name,
                        )
                    rows = session.execute_write(
                        lambda tx: tx.run(query, kwargs).data()
                    )
                for row in rows:
                    if (
                        row.get("failedBatches", 0)
                        or row.get("failedOperations", 0)
                        or row.get("wasTerminated", False)
                    ):
                        raise RuntimeError(
                            f"PromG batch failed: {row.get('errorMessages') or row.get('batchErrors') or 'batch terminated'}"
                        )
                return rows
            except Exception:
                logger.exception(
                    "PromG query failed phase=%s generator=%s database=%s parameter_keys=%s\nQUERY:\n%s",
                    phase,
                    getattr(self, "query_name", "HTTP validation"),
                    self.db_name,
                    sorted(kwargs),
                    redact(query),
                )
                if original != query:
                    logger.error("Original PromG schema query:\n%s", redact(original))
                raise
            finally:
                name = getattr(self, "query_name", "HTTP validation")
                metric = metrics["queries"].setdefault(
                    name, {"calls": 0, "seconds": 0.0}
                )
                metric["calls"] += 1
                metric["seconds"] += perf_counter() - query_started

    # PromG 2.2.3's factory incorrectly passes config.user as db_name.
    connection = Connection(
        uri=conf.uri,
        db_name=conf.db_name,
        user=conf.user,
        password=conf.password,
        verbose=conf.verbose,
        batch_size=conf.batch_size,
    )
    phase = "HTTP CSV accessibility validation"
    try:
        with serve_csv(
            directory,
            settings["csv_public_url"],
            settings["csv_token"],
            settings["csv_port"],
            metrics=metrics.setdefault("http", {}),
        ) as url_for:
            print(f"PromG phase: {phase}", flush=True)
            probe = directory / "soup-access-check.csv"
            probe.write_text("soup_probe\naccessible\n", encoding="utf-8")
            try:
                rows = connection._exec_query(
                    "LOAD CSV WITH HEADERS FROM $url AS row RETURN row.soup_probe AS value",
                    url=url_for(probe.name),
                )
                if rows != [{"value": "accessible"}]:
                    raise RuntimeError(
                        "Neo4j could not read the temporary HTTP CSV accessibility check"
                    )
            finally:
                probe.unlink(missing_ok=True)
            Performance.set_up_performance(config=conf)
            semantic = SemanticHeader.create_semantic_header(config=conf)
            descriptions = DatasetDescriptions(config=conf)
            phase = "constraints"
            print(f"PromG phase: {phase}", flush=True)
            with measure("promg_constraints"):
                DBManagement(db_connection=connection).set_constraints()
            graph = OcedPg(
                database_connection=connection,
                dataset_descriptions=descriptions,
                semantic_header=semantic,
                use_sample=conf.use_sample,
                use_preprocessed_files=conf.use_preprocessed_files,
                store_files=False,  # This private run never reuses PromG’s pickle cache.
                import_directory=str(directory),
            )
            for structure in descriptions.structures:
                structure.read_data_set = measured_csv(structure.read_data_set)
            graph.data_importer._save_log_grouped_by_labels = measured_csv(
                graph.data_importer._save_log_grouped_by_labels
            )
            phase = "load and transform"
            print(f"PromG phase: {phase}", flush=True)
            with measure("promg_loading_transform"):
                graph.load_and_transform()
            phase = "DF creation"
            print(f"PromG phase: {phase}", flush=True)
            with measure("promg_df"):
                graph.create_df_edges()
    except Exception:
        print(f"PromG failed during: {phase}", file=sys.stderr, flush=True)
        raise
    finally:
        try:
            temporary = metrics_path.with_suffix(".tmp")
            temporary.write_text(json.dumps(metrics), encoding="utf-8")
            temporary.replace(metrics_path)
        finally:
            connection.driver._driver.close()


if __name__ == "__main__":
    main(sys.argv[1])
